import { z } from "zod";

/**
 * Stream event types emitted by model provider adapters.
 */
export const StreamEventSchema = z.enum([
  "text_delta",
  "tool_call_delta",
  "usage",
  "finish",
  "error"
]);
export type StreamEvent = z.infer<typeof StreamEventSchema>;

/**
 * Normalized token usage accounting.
 * When actual token counts are unavailable from the provider,
 * tokens are set to -1 or marked with is_estimated: true.
 */
export const TokenUsageSchema = z.object({
  prompt_tokens: z.number().int(),
  completion_tokens: z.number().int(),
  total_tokens: z.number().int(),
  is_estimated: z.boolean().optional()
});
export type TokenUsage = z.infer<typeof TokenUsageSchema>;

/**
 * Normalized provider error across upstream model vendors.
 */
export const NormalizedErrorSchema = z.object({
  code: z.string(),
  message: z.string(),
  retryable: z.boolean(),
  status: z.number().int().optional(),
  details: z.record(z.string(), z.unknown()).optional()
});
export type NormalizedError = z.infer<typeof NormalizedErrorSchema>;

/**
 * Model capability descriptor for context planning and dispatch.
 */
export const ModelCapabilitySchema = z.object({
  supports_streaming: z.boolean(),
  supports_tools: z.boolean(),
  supports_vision: z.boolean().optional(),
  max_context_tokens: z.number().int().positive(),
  max_output_tokens: z.number().int().positive()
});
export type ModelCapability = z.infer<typeof ModelCapabilitySchema>;

/**
 * Tool call delta emitted during streaming.
 */
export const ToolCallDeltaSchema = z.object({
  id: z.string().optional(),
  name: z.string().optional(),
  arguments_delta: z.string().optional(),
  index: z.number().int().optional()
});
export type ToolCallDelta = z.infer<typeof ToolCallDeltaSchema>;

/**
 * Tool call proposal generated by a model.
 * NOTE: The provider adapter only parses and yields proposals.
 * Execution is strictly delegated to the tool runner.
 */
export const ToolCallProposalSchema = z.object({
  id: z.string().optional(),
  name: z.string(),
  arguments: z.union([z.record(z.string(), z.unknown()), z.string()])
});
export type ToolCallProposal = z.infer<typeof ToolCallProposalSchema>;

/**
 * Discriminated stream chunk yield by generateStream.
 */
export type StreamChunk =
  | { type: "text_delta"; text: string }
  | { type: "tool_call_delta"; tool_call: ToolCallDelta }
  | { type: "usage"; usage: TokenUsage }
  | { type: "finish"; finish_reason: "stop" | "tool_calls" | "length" | "cancelled" | "error" }
  | { type: "error"; error: NormalizedError };

/**
 * Message input passed to model generation.
 */
export const ProviderMessageRoleSchema = z.enum(["system", "user", "assistant", "tool"]);
export type ProviderMessageRole = z.infer<typeof ProviderMessageRoleSchema>;

export const ProviderMessageSchema = z.object({
  role: ProviderMessageRoleSchema,
  content: z.string(),
  tool_calls: z.array(ToolCallProposalSchema).optional(),
  tool_call_id: z.string().optional(),
  name: z.string().optional()
});
export type ProviderMessage = z.infer<typeof ProviderMessageSchema>;

/**
 * Tool declaration specification passed to the provider.
 */
export const ProviderToolDefinitionSchema = z.object({
  name: z.string(),
  description: z.string(),
  parameters: z.record(z.string(), z.unknown()).optional()
});
export type ProviderToolDefinition = z.infer<typeof ProviderToolDefinitionSchema>;

/**
 * Request options for streaming content generation.
 */
export interface GenerateStreamOptions {
  model?: string | undefined;
  messages: ProviderMessage[];
  tools?: ProviderToolDefinition[] | undefined;
  temperature?: number | undefined;
  max_tokens?: number | undefined;
  signal?: AbortSignal | undefined;
}

/**
 * Public provider health and availability status (safe for browser exposure).
 * Never exposes raw secret keys or tokens.
 */
export const ProviderStatusSchema = z.object({
  id: z.string(),
  name: z.string(),
  available: z.boolean(),
  configured: z.boolean(),
  models: z.array(z.string()),
  default_model: z.string(),
  error: z.string().optional(),
  latency_ms: z.number().optional()
});
export type ProviderStatus = z.infer<typeof ProviderStatusSchema>;

/**
 * Contract for a pluggable model provider adapter.
 */
export interface ProviderAdapter {
  readonly id: string;
  readonly name: string;
  readonly configured: boolean;
  readonly models: string[];
  readonly defaultModel: string;

  getCapabilities(model?: string): ModelCapability;
  checkHealth(): Promise<ProviderStatus>;
  generateStream(options: GenerateStreamOptions): AsyncIterable<StreamChunk>;
}

/**
 * Schema for testing provider connection.
 */
export const ProviderTestInputSchema = z.object({
  provider: z.string().optional(),
  model: z.string().optional()
});
export type ProviderTestInput = z.infer<typeof ProviderTestInputSchema>;

export const ProviderTestResultSchema = z.object({
  success: z.boolean(),
  provider: z.string(),
  model: z.string(),
  latency_ms: z.number(),
  message: z.string()
});
export type ProviderTestResult = z.infer<typeof ProviderTestResultSchema>;
